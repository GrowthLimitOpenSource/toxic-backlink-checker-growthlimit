import type { DomainGroup, ExistingDisavow } from "./types";

export function parseDisavow(input: string, auditedDomain: string): ExistingDisavow {
  const result: ExistingDisavow = { comments: [], domains: [], urls: [], invalid: [] };
  const seen = new Set<string>();
  input.split(/\r?\n/).forEach((raw, index) => {
    const line = raw.trim();
    if (!line) return;
    if (line.startsWith("#")) { result.comments.push(line); return; }
    let value = line;
    let host = "";
    try {
      if (line.toLowerCase().startsWith("domain:")) {
        host = line.slice(7).trim().toLowerCase().replace(/^www\./, "");
        if (!validHost(host)) throw new Error("Domain entries must use domain:example.com.");
        value = `domain:${host}`;
      } else {
        const url = new URL(line);
        if (!["http:", "https:"].includes(url.protocol) || url.username || url.password) throw new Error("URL must be public HTTP(S) without credentials.");
        host = url.hostname.toLowerCase().replace(/^www\./, "");
        value = url.toString();
      }
      if (host === auditedDomain || host.endsWith(`.${auditedDomain}`)) throw new Error("The audited site cannot disavow itself.");
      if (["localhost", "127.0.0.1", "0.0.0.0"].includes(host) || host.endsWith(".local")) throw new Error("Private host entries are not accepted.");
      if (seen.has(value)) return;
      seen.add(value);
      if (value.startsWith("domain:")) result.domains.push(value); else result.urls.push(value);
    } catch (error) { result.invalid.push({ line: index + 1, value: line, reason: error instanceof Error ? error.message : "Invalid entry." }); }
  });
  return result;
}

function validHost(host: string) { return /^(?=.{4,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i.test(host); }

export function renderDisavow(groups: DomainGroup[], existing: ExistingDisavow): string {
  const lines = ["# Draft generated by Toxic Backlink Checker by GrowthLimit.com", "# HUMAN REVIEW REQUIRED. Uploading replaces the prior disavow file.", ...existing.comments, ...existing.domains, ...existing.urls];
  for (const group of groups) {
    if (!group.approved) continue;
    if (group.classification === "DISAVOW_DOMAIN") lines.push(`domain:${group.domain}`);
    if (group.classification === "DISAVOW_URL") lines.push(...group.links.map((x) => x.urlFrom));
  }
  return [...new Set(lines)].join("\n") + "\n";
}
